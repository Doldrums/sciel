"""Task discovery, contract validation, and task_hash (identity by content)."""

from __future__ import annotations

import hashlib
import os
from dataclasses import dataclass, field

import yaml


REQUIRED_FIELDS = ["suite", "name", "origin", "primary_metric"]
ORIGINS = {"math", "oe", "highlight", "heavy"}


@dataclass
class TaskSpec:
    root: str
    suite: str
    name: str
    origin: str
    primary_metric: str
    case_metrics: list[str] = field(default_factory=list)
    tiers: list[str] = field(default_factory=list)
    resources: str = "cpu"
    stochastic: bool = True
    confirm_n: int = 10
    smoke_timeout: float = 30.0
    full_timeout: float = 120.0
    confirm_timeout: float = 300.0
    cpu_seconds: int | None = None
    mem_bytes: int | None = None
    # Wall-clock a SINGLE run of the candidate is allowed, when that is tighter than
    # the stage timeout. A multi-trial evaluator runs the program N times inside one
    # stage, so the stage cap is not what the program must fit in, and the prompt's
    # compute-budget directive was quoting the wrong number in both directions.
    per_run_timeout: float | None = None
    known_best: float | None = None
    license: str = ""
    task_hash: str = ""
    # Research-facing semantics only. The evaluator remains the score authority.
    research_metric: dict | None = None
    # Evaluator-owned full-output evidence; absent metadata never turns scores
    # or case vectors into an output-equivalence test.
    output_identity: dict | None = None
    # Public objective/interface/measurement rules, never hidden instance data.
    task_prompt: str | None = None

    @property
    def evaluator_path(self) -> str:
        return os.path.join(self.root, "evaluator.py")

    @property
    def initial_program_path(self) -> str:
        return os.path.join(self.root, "initial_program.py")

    @property
    def qualified_name(self) -> str:
        return f"{self.suite}/{self.name}"


def _canonical_yaml_bytes(cfg: dict) -> bytes:
    return yaml.safe_dump(cfg, sort_keys=True, default_flow_style=False).encode()


def compute_task_hash(root: str, cfg: dict) -> str:
    h = hashlib.sha256()
    h.update(_canonical_yaml_bytes(cfg))
    for rel in ("evaluator.py", "initial_program.py"):
        p = os.path.join(root, rel)
        if os.path.exists(p):
            with open(p, "rb") as f:
                h.update(rel.encode())
                h.update(f.read())
    assets = os.path.join(root, "assets")
    if os.path.isdir(assets):
        for dirpath, dirs, files in os.walk(assets):
            # Importing an asset must not change the identity of its source.
            # Keep all real assets (including native binaries), but omit Python's
            # generated bytecode both in __pycache__ and legacy adjacent files.
            dirs[:] = sorted(name for name in dirs if name != "__pycache__")
            for name in sorted(files):
                if name.endswith((".pyc", ".pyo")):
                    continue
                p = os.path.join(dirpath, name)
                with open(p, "rb") as f:
                    rel = os.path.relpath(p, root).replace(os.sep, "/")
                    h.update(rel.encode())
                    h.update(f.read())
    return h.hexdigest()


def load_task(root: str) -> TaskSpec:
    from ..evidence.measurement import validate_research_metric
    from .output_identity import validate_output_identity_config
    from .task_prompt import validate_task_prompt
    from .sandbox import validate_stage_limits

    cfg_path = os.path.join(root, "task.yaml")
    if not os.path.exists(cfg_path):
        raise FileNotFoundError(f"no task.yaml in {root}")
    with open(cfg_path) as f:
        cfg = yaml.safe_load(f)
    if cfg is None:
        cfg = {}
    if type(cfg) is not dict:
        raise ValueError(f"{root}: task.yaml must be a mapping")
    missing = [k for k in REQUIRED_FIELDS if k not in cfg]
    if missing:
        raise ValueError(f"{root}: task.yaml missing {missing}")
    if cfg["origin"] not in ORIGINS:
        raise ValueError(f"{root}: origin '{cfg['origin']}' not in {ORIGINS}")
    stochastic = cfg.get("stochastic", True)
    if type(stochastic) is not bool:
        raise ValueError(f"{root}: stochastic must be a boolean")
    confirm_n = cfg.get("confirm_n", 10)
    if type(confirm_n) is not int or confirm_n <= 0:
        raise ValueError(f"{root}: confirm_n must be a positive integer")
    cpu_seconds, mem_bytes = cfg.get("cpu_seconds"), cfg.get("mem_bytes")
    timeouts = {}
    for name, default in (("smoke_timeout", 30.0), ("full_timeout", 120.0),
                          ("confirm_timeout", 300.0)):
        value = cfg.get(name, default)
        try:
            validate_stage_limits(value, confirm_n, cpu_seconds, mem_bytes)
        except ValueError as exc:
            raise ValueError(f"{root}: {name}: {exc}") from exc
        timeouts[name] = float(value)
    per_run_timeout = cfg.get("per_run_timeout")
    if per_run_timeout is not None:
        try:
            validate_stage_limits(per_run_timeout)
        except ValueError as exc:
            raise ValueError(f"{root}: per_run_timeout: {exc}") from exc
    known = cfg.get("known_best")
    spec = TaskSpec(
        root=root,
        suite=cfg["suite"],
        name=cfg["name"],
        origin=cfg["origin"],
        primary_metric=cfg["primary_metric"],
        case_metrics=list(cfg.get("case_metrics", [])),
        tiers=list(cfg.get("tiers", [])),
        resources=cfg.get("resources", "cpu"),
        stochastic=stochastic,
        confirm_n=confirm_n,
        smoke_timeout=timeouts["smoke_timeout"],
        full_timeout=timeouts["full_timeout"],
        confirm_timeout=timeouts["confirm_timeout"],
        cpu_seconds=cpu_seconds,
        mem_bytes=mem_bytes,
        per_run_timeout=per_run_timeout,
        known_best=float(known) if known is not None else None,
        license=cfg.get("license", ""),
        task_hash=compute_task_hash(root, cfg),
        research_metric=validate_research_metric(cfg.get("research_metric")),
        output_identity=validate_output_identity_config(cfg.get('output_identity')),
        task_prompt=validate_task_prompt(cfg.get('task_prompt')),
    )
    _validate_files(spec)
    return spec


# Stages the cascade actually runs, in order. `tiers` is a declaration ABOUT this,
# not an instruction to it: the cascade is smoke -> full -> confirm regardless. The
# list was parsed and never read, so seven task.yaml files advertised a `mini` tier
# that does not exist and one declared only `smoke` while `full` was still invoked.
CASCADE_STAGES = ("smoke", "full", "confirm")


def _validate_tiers(spec: TaskSpec) -> None:
    if not spec.tiers:
        return
    unknown = [t for t in spec.tiers if t not in CASCADE_STAGES]
    if unknown:
        raise ValueError(
            f"{spec.root}: task.yaml declares tiers {unknown} that the cascade does "
            f"not run; it runs {list(CASCADE_STAGES)}")
    # confirm is optional (only stochastic tasks reach it); smoke and full are not
    for required in ("smoke", "full"):
        if required not in spec.tiers:
            raise ValueError(
                f"{spec.root}: task.yaml omits the '{required}' tier, but the cascade "
                f"always runs it; declare it or remove the tiers list")


def _validate_files(spec: TaskSpec) -> None:
    for p in (spec.evaluator_path, spec.initial_program_path):
        if not os.path.exists(p):
            raise ValueError(f"{spec.root}: missing {os.path.basename(p)}")
    _validate_tiers(spec)


def discover(tasks_root: str) -> list[TaskSpec]:
    found = []
    for dirpath, _dirs, files in os.walk(tasks_root):
        if "task.yaml" in files:
            found.append(load_task(dirpath))
    return sorted(found, key=lambda s: s.qualified_name)


def determinism_check(spec: TaskSpec, python: str | None = None,
                      program_path: str | None = None) -> dict:
    """Run one program twice and compare.

    `program_path` defaults to the task's seed, and that default is the check's
    weakness: a seed that returns a constant is deterministic no matter how random the
    task is. heilbronn's seed returns an all-zero point set, so the check passed while
    real evolved programs on that task scored 0.54 to 0.78 across repeats of the SAME
    program -- the task ran for its whole history declared deterministic, which kept
    the confirm stage switched off and let a lucky draw stand as a record.

    `informative` says whether the check could have detected anything. Pass a real
    evolved program to get an answer that means something."""
    from .sandbox import run_stage
    probe = program_path or spec.initial_program_path
    a = run_stage(spec.evaluator_path, "smoke", probe,
                  timeout=spec.smoke_timeout, cpu_seconds=spec.cpu_seconds,
                  mem_bytes=spec.mem_bytes, python=python)
    b = run_stage(spec.evaluator_path, "smoke", probe,
                  timeout=spec.smoke_timeout, cpu_seconds=spec.cpu_seconds,
                  mem_bytes=spec.mem_bytes, python=python)
    runs = a.ok and b.ok
    deterministic = runs and abs(a.score - b.score) < 1e-9
    # `valid` used to be `deterministic or stochastic`, which never consulted ok: a
    # task whose evaluator raised on import, or whose seed program was broken, scored
    # 0.0 twice and still validated as long as it declared itself stochastic.
    # A pair of zero scores is the signature of a probe that exercises nothing: two
    # runs of a constant program agree trivially. A disagreement is always
    # informative, whatever the scores.
    informative = runs and (not deterministic or a.score != 0.0 or b.score != 0.0)
    return {
        "deterministic": deterministic,
        "runs": runs,
        "informative": informative,
        "probe": os.path.basename(probe),
        "score_a": a.score,
        "score_b": b.score,
        "error": (a.stderr or b.stderr or "")[:400] if not runs else "",
        "stochastic_declared": spec.stochastic,
        "smoke_timing": a.timing,
        "valid": runs and (deterministic or spec.stochastic),
    }
