    "numerator (for example sum_radii). Null/missing metric or cases means unknown; do not "
    "infer units from old prose. evaluation.reached/confirmed/raw_first_score describe the "
    "returned cascade result, which can aggregate trials, not all intermediate stages. "
    "For eval_failed, retained score/cases are diagnostic sentinels, not quality evidence. "
