_LESSON_FORMAT = (
    f"lessons is a list of at most {MAX_LESSONS} objects, each with four required fields: rule "
    f"(nonempty string, at most {MAX_TEXT_CHARS} characters), polarity ('positive' or "
    "'negative', about the observed effect, not forecast matching), scope ('branch' or "
    "'global'), and evidence_ids (nonempty list of unique supplied experiment IDs, "
    f"at most {MAX_EVIDENCE_IDS}, each at most {MAX_ID_CHARS} characters without whitespace). "
    "The optional branch field may be omitted: the controller infers and validates it from "
    "evidence. If present, use the exact evidence branch ID for branch scope, or null for "
    "global scope; no other extra keys are allowed. "
    "Use branch scope unless the supplied evidence supports broader scope; scope is a "
    "request, not authorization to promote a lesson. Use lessons=[] when evidence does "
    "not support a lesson. For ordinary experiment evidence, EVERY cited experiment "
    "must have status='evaluated' and a "
    "strictly positive actual_delta for positive polarity, or a strictly negative "
    "actual_delta for negative polarity. A zero/null delta supports neither. Do not mix "
    "positive and negative deltas in one proposal: describe conflicting observations "
    "as separate scoped lessons. Branch scope requires exactly ONE evidence branch; "
    "global scope requires evidence from at least TWO distinct branches. "
    "Each rule must connect the specific observed source change or condition to its "
    "measured outcome and the limits of that observation. When available, name the "
    "controlled_change operation and its parent_policy -> target_policy (or equivalent "
    "readable before/after values). For ordinary experiments, state the actual score direction and delta in the "
    "declared score units; for typed paired groups use their separate raw/certified paired "
    "measurements instead. Restrict the finding to the cited observation(s). For "
    "a generic edit, describe only the visible change; if it is missing or truncated, "
    "state that limit or return lessons=[]. A rule that only says the forecast matched "
    "or missed is not a reusable observation about the code change. Do not turn one "
    "loss into an untested recommendation, predict an untested smaller/larger change, "
    "or invent an optimal parameter. "
    "If typed paired comparison IDs are supplied, only full challenger dominance "
    "supports positive polarity and full comparator dominance supports negative "
    "polarity. Mixed/tied/incomplete groups support neither; never invent ordinary "
    "actual_delta for a group. One "
    "group counts as one source on its recorded branch, even with three seeds. "
    "IDs and retirement requests are validated by the knowledge base."
)
