"""Turn one Python file with `solve()` and `score(result)` into a task package the engine can search.

The file is copied twice: as the seed program the search rewrites, and as a frozen problem module the
evaluator reads `score` (and an optional `metrics`) from. A candidate that edits its own `score` changes nothing.
"""

from __future__ import annotations

import ast
import hashlib
import shutil
from pathlib import Path

import yaml

from .eval.task_prompt import MAX_TASK_PROMPT_CHARS

SUITE = "local"

EVALUATOR = '''"""Score a candidate's solve() with the frozen score() of problem.py. Generated by sciel."""

import math
from pathlib import Path

from sciel.candidate_modules import load_candidate

PROBLEM = str(Path(__file__).resolve().with_name("problem.py"))


def _run(program_path, stage):
    try:
        program = load_candidate(program_path, "candidate_" + stage)
        problem = load_candidate(PROBLEM, "problem_" + stage)
        result = program.solve()
        value = float(problem.score(result))
        if not math.isfinite(value):
            raise ValueError(f"score is not finite: {value}")
        cases = {"combined_score": value}
        if hasattr(problem, "metrics"):
            for key, metric in dict(problem.metrics(result)).items():
                if isinstance(metric, (int, float)) and math.isfinite(metric):
                    cases[str(key)] = float(metric)
    except Exception as exc:
        return {"ok": False, "score": 0.0, "cases": {"combined_score": 0.0},
                "artifacts": {"error": f"{type(exc).__name__}: {exc}"[:2000]}}
    return {"ok": True, "score": value, "cases": cases, "artifacts": {}}


def smoke(program_path):
    return _run(program_path, "smoke")


def full(program_path):
    return _run(program_path, "full")


def confirm(program_path, n=1):
    return _run(program_path, "confirm")
'''

CONTRACT = ("Improve solve() in this program so that score(solve()) is as high as possible. "
            "score() and metrics() are fixed by the evaluator: the copies in this file are for reference, "
            "and editing them changes nothing. Higher is better; an exception or a non-finite score counts as 0. "
            "solve() takes no arguments. Smoke runs must finish within {smoke:g} s and full runs within {full:g} s.")


class TaskFileError(ValueError):
    """The file cannot become a task; the message says what it needs."""


def _check(source: str, path: Path):
    try:
        tree = ast.parse(source, filename=str(path))
    except SyntaxError as exc:
        raise TaskFileError(f"{path} does not parse: {exc}") from None
    names = {node.name for node in tree.body if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))}
    missing = [name for name in ("solve", "score") if name not in names]
    if missing:
        raise TaskFileError(f"{path} must define {' and '.join(missing)}(): "
                            "solve() returns a result, score(result) returns a number, higher is better")
    return ast.get_docstring(tree) or ""


def build(program: str | Path, root: str | Path, *, smoke=60.0, full=300.0, stochastic=False) -> str:
    """Write the task package under `root`/local/<name>; return its task name for configs."""
    path = Path(program).resolve()
    source = path.read_text()
    about = _check(source, path)
    digest = hashlib.sha256(source.encode()).hexdigest()[:8]
    name = f"{path.stem}_{digest}"
    task_dir = Path(root) / SUITE / name
    if not (task_dir / "task.yaml").exists():
        task_dir.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, task_dir / "problem.py")
        shutil.copyfile(path, task_dir / "initial_program.py")
        (task_dir / "evaluator.py").write_text(EVALUATOR)
        prompt = CONTRACT.format(smoke=smoke, full=full)
        if about:
            prompt = (" ".join(about.split()) + "\n\n" + prompt)
        prompt = prompt[-MAX_TASK_PROMPT_CHARS:]
        spec = {"suite": SUITE, "name": name, "origin": SUITE, "primary_metric": "combined_score",
                "case_metrics": ["combined_score"], "tiers": ["smoke", "full"], "resources": "cpu",
                "stochastic": bool(stochastic), "confirm_n": 3 if stochastic else 1,
                "smoke_timeout": float(smoke), "full_timeout": float(full), "confirm_timeout": float(full) * 3,
                "task_prompt": prompt, "license": "user supplied"}
        (task_dir / "task.yaml").write_text(yaml.safe_dump(spec, sort_keys=False, allow_unicode=True))
    return f"{SUITE}/{name}"
