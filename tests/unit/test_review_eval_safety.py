import tracemalloc

import numpy as np
import pytest

from sciel.engine.repeat_support import (EVALUATOR_SHA, LEGACY_GEOMETRY_EVALUATOR_SHA,
    TRACED_BODY_TASK_HASH, OPTIMIZER_TRACED_TASK_HASH, validate_circle_task)
from sciel.eval.native_geometry import validate_geometry
from sciel.eval.registry import compute_task_hash, load_task
from sciel.eval.sandbox import run_stage


ROOT = Path(__file__).resolve().parents[2]


def circle_evaluator(task):
    path = ROOT / "tasks/oe" / task / "evaluator.py"
    spec = importlib.util.spec_from_file_location("precision_fixture", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.mark.parametrize("task", ["circle_packing", "circle_packing_seed"])
@pytest.mark.parametrize("violation", ["wall", "pair"])
def test_low_precision_geometry_cannot_round_away_a_violation(tmp_path, task, violation):
    change = ("c[0] = [.8, .5]; r[0] = .2003" if violation == "wall" else
              "c[0] = [.01, .01]; c[1] = [.01022, .01022]; r[:2] = .00016")
    source = tmp_path / "candidate.py"
    source.write_text("import numpy as np\ndef run_packing():\n"
        "    c = np.zeros((26, 2), dtype=np.float16)\n"
        "    r = np.zeros(26, dtype=np.float16)\n"
        f"    {change}\n    return c, r, r.sum()\n")
    result = circle_evaluator(task).smoke(str(source))
    assert result["ok"] and result["score"] == 0
    assert result["cases"]["validity"] == 0
    if task == "circle_packing":
        geometry = json.loads(result["artifacts"]["native_geometry"])
        assert geometry["centers_dtype"] == "float16"
        assert validate_geometry(geometry)["native_validity"] is False
        # Historical evidence remains readable under its original evaluator;
        # neither its old validity nor its score is silently relabelled.
        old = dict(geometry, evaluator_sha256=LEGACY_GEOMETRY_EVALUATOR_SHA,
                   native_validity=True)
        old["native_sum_radii"] = float(np.sum(np.asarray(old["numeric"]["radii"], dtype=np.float16)))
        old["native_score"] = old["native_sum_radii"] / 2.635
        assert validate_geometry(old)["native_validity"] is True
        assert geometry["evaluator_sha256"] == EVALUATOR_SHA


def test_valid_float32_score_keeps_native_reduction_and_captured_dtype(tmp_path):
    source = tmp_path / "valid.py"
    source.write_text("import numpy as np\ndef run_packing():\n"
        "    c = np.array([(.1+.16*(i%6), .1+.2*(i//6)) for i in range(26)], dtype=np.float32)\n"
        "    r = np.full(26, .01, dtype=np.float32)\n    return c, r, r.sum()\n")
    result = circle_evaluator("circle_packing").smoke(str(source))
    assert result["cases"]["validity"] == 1
    expected = float(np.sum(np.full(26, .01, dtype=np.float32)))
    assert result["score"] == expected / 2.635
    geometry = validate_geometry(json.loads(result["artifacts"]["native_geometry"]))
    assert geometry["radii_dtype"] == "float32"
    assert geometry["native_sum_radii"] == expected


@pytest.mark.parametrize("profile,expected", [
    ("paired_restart_trace/1", TRACED_BODY_TASK_HASH),
    ("paired_restart_trace/2", OPTIMIZER_TRACED_TASK_HASH),
])
def test_corrected_evaluator_pins_traced_profiles_without_running_candidates(tmp_path, profile, expected):
    from sciel.hypothesis.circle_source_family import builder_for_profile
    builder = builder_for_profile(profile)
    for name in ("task.yaml", "evaluator.py"):
        (tmp_path / name).write_bytes((ROOT / "tasks/oe/circle_packing" / name).read_bytes())
    (tmp_path / "initial_program.py").write_text(builder.source_for())
    task = load_task(str(tmp_path))
    assert task.task_hash == expected
    validate_circle_task(task, initial_source_policy=builder.OPERATION)


def test_asset_import_caches_do_not_change_hash_but_source_and_binary_assets_do(tmp_path):
    assets = tmp_path / "assets"
    assets.mkdir()
    source = assets / "oracle.py"
    source.write_text("VALUE = 7\n")
    cfg = {"suite": "test", "name": "asset"}
    original = compute_task_hash(str(tmp_path), cfg)
    spec = importlib.util.spec_from_file_location("cached_oracle_fixture", source)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    # Also exercise legacy cache files, independently of interpreter cache flags.
    (assets / "oracle.pyc").write_bytes(b"generated bytecode")
    (assets / "oracle.pyo").write_bytes(b"generated optimized bytecode")
    cache = assets / "__pycache__"
    cache.mkdir(exist_ok=True)
    (cache / "interpreter-cache").write_bytes(b"cache")
    assert compute_task_hash(str(tmp_path), cfg) == original
    source.write_text("VALUE = 8\n")
    changed = compute_task_hash(str(tmp_path), cfg)
    assert changed != original
    (assets / "weights.bin").write_bytes(b"real model data")
    assert compute_task_hash(str(tmp_path), cfg) != changed


@pytest.mark.parametrize("crash", [False, True])
def test_stage_discards_stdout_and_retains_only_bounded_stderr(tmp_path, crash):
    path = tmp_path / "evaluator.py"
    path.write_text("import os\ndef smoke(program):\n"
        "    block = b'x' * 65536\n"
        "    for _ in range(32):\n        os.write(1, block)\n        os.write(2, block)\n"
        "    os.write(2, b'\\nTAIL-SENTINEL\\n')\n"
        + ("    os._exit(7)\n" if crash else "    return {'ok': True, 'score': .5}\n"))
    tracemalloc.start()
    try:
        result = run_stage(str(path), "smoke", "unused", timeout=2, python=sys.executable)
        _, peak = tracemalloc.get_traced_memory()
    finally:
        tracemalloc.stop()
    assert peak < 2 * 1024 * 1024, "parent retained output proportional to candidate noise"
    assert result.ok is not crash
    assert "TAIL-SENTINEL" in result.stderr
    assert len(result.stderr) < 2100
    assert not any(t.name == "sciel-evaluator-stderr" for t in threading.enumerate())
