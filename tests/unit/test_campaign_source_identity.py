"""Source identity and artifact verification do not depend on campaign runners."""
from pathlib import Path

import pytest

from sciel.campaign import identity


def verify_source(root, source):
    identity.verify_files(root, source['files'], exact_root='src',
                          suffixes=('.py', '.txt'), exclude_build_metadata=True)
    identity.verify_files(root, source['project_files'])


@pytest.fixture
def frozen_checkout(tmp_path, monkeypatch):
    root = tmp_path / 'checkout'
    (root / 'src/templates').mkdir(parents=True)
    (root / 'src/module.py').write_text('VALUE = 1\n')
    (root / 'src/templates/prompt.txt').write_text('real prompt template\n')
    (root / 'pyproject.toml').write_text('[project]\nname = "fixture"\nversion = "0.1"\n')
    # Model tracked and untracked build metadata without creating git commits.
    def git_output(command, **kwargs):
        if command[1] == 'rev-parse':
            return 'fixture-commit\n'
        if command[1] == 'diff':
            return 'src/sciel.egg-info/SOURCES.txt\0'
        if command[1] == 'ls-files':
            return 'src/package.dist-info/extra.txt\0'
        raise AssertionError(command)
    monkeypatch.setattr(identity.subprocess, 'check_output', git_output)
    source = identity.source_identity(root)
    assert not source['dirty']
    verify_source(root, source)
    return root, source


@pytest.mark.parametrize('metadata', ['sciel.egg-info', 'package.dist-info', '__pycache__'])
def test_metadata_regeneration_does_not_change_source_identity(frozen_checkout, metadata):
    root, source = frozen_checkout
    directory = root / 'src' / metadata
    directory.mkdir()
    (directory / 'SOURCES.txt').write_text('generated by build\n')
    (directory / 'requires.txt').write_text('dependency==1\n')
    (directory / 'generated.py').write_text('generated = True\n')
    assert identity.source_identity(root) == source
    verify_source(root, source)
    (directory / 'SOURCES.txt').unlink()
    (directory / 'requires.txt').write_text('dependency==2\n')
    (directory / 'new.txt').write_text('new metadata\n')
    assert identity.source_identity(root) == source
    verify_source(root, source)


@pytest.mark.parametrize('added', ['src/new_module.py', 'src/templates/new_prompt.txt'])
def test_new_real_source_remains_detectable(frozen_checkout, added):
    root, source = frozen_checkout
    (root / added).write_text('new real source\n')
    assert identity.source_identity(root)['source_sha256'] != source['source_sha256']
    with pytest.raises(ValueError, match='file set changed'):
        verify_source(root, source)


def test_project_dependency_change_is_separately_frozen_and_verified(frozen_checkout, monkeypatch):
    root, source = frozen_checkout
    project = root / 'pyproject.toml'
    assert source['project_files'] == {'pyproject.toml':identity.file_sha(project)}
    project.write_text('[project]\nname = "fixture"\ndependencies = ["new-dependency"]\n')
    previous = identity.subprocess.check_output
    def git_output(command, **kwargs):
        if command[1] == 'diff':
            assert 'pyproject.toml' in command
            return 'pyproject.toml\0'
        return previous(command, **kwargs)
    monkeypatch.setattr(identity.subprocess, 'check_output', git_output)
    changed = identity.source_identity(root)
    assert changed['source_sha256'] == source['source_sha256']
    assert changed['project_files'] != source['project_files'] and changed['dirty']
    with pytest.raises(ValueError, match='pyproject.toml'):
        verify_source(root, source)


def test_metadata_exclusion_does_not_hide_frozen_task_or_model_assets(tmp_path):
    (tmp_path / 'frozen').mkdir()
    identity.verify_files(tmp_path, {}, exact_root='frozen')
    added = tmp_path / 'frozen/task-assets.egg-info'
    added.mkdir()
    (added / 'data.txt').write_text('task input, not package build output\n')
    with pytest.raises(ValueError, match='file set changed'):
        identity.verify_files(tmp_path, {}, exact_root='frozen')
